import { defaultGlassPresetId, getCatalog, type StartingPresetId } from '@ombelle/catalog'
import { glassContrastOnScene, normalizeColor, type GlassSceneRange } from '@ombelle/compiler'
import type { Preset } from '@ombelle/contracts'
import type { PresetBackdrop } from '../preset-editor/preview-protocol'
import { glassBackdropOptions, glassPresetBackdrop, type GlassPreviewMode } from './glass-presets'

/**
 * The darkest and brightest pixel of each glass preview scene, per mode, as the
 * gamma-encoded grey of the same relative luminance, so the backdrop filter can run on
 * it. Sampled on a 32 × 20 grid over the central 80 % of a 1280 × 800 preview in
 * Chromium. Generated by pnpm measure:glass-scenes; tests/e2e/glass-scenes.spec.ts
 * re-measures the scenes and fails when this table no longer matches their art.
 */
export const glassSceneRanges: Record<PresetBackdrop, Record<'light' | 'dark', GlassSceneRange>> = {
  kit: { light: { low: 0.2101, high: 0.759 }, dark: { low: 0.2101, high: 0.759 } },
  mist: { light: { low: 0.7113, high: 0.9438 }, dark: { low: 0.7113, high: 0.9438 } },
  dawn: { light: { low: 0.701, high: 0.936 }, dark: { low: 0.701, high: 0.936 } },
  grid: { light: { low: 0.68, high: 0.96 }, dark: { low: 0.68, high: 0.96 } },
  peach: { light: { low: 0.5226, high: 0.7032 }, dark: { low: 0.5226, high: 0.7032 } },
  prism: { light: { low: 0.1803, high: 0.8572 }, dark: { low: 0.1803, high: 0.8572 } },
  night: { light: { low: 0.0492, high: 0.643 }, dark: { low: 0.0492, high: 0.643 } },
}

/** The lab material presets: their ink was tuned to read on their own scene without the plate. */
export const labStartingPresets: readonly StartingPresetId[] = [
  defaultGlassPresetId,
  'builtin-liquid-glass-givre',
  'builtin-liquid-glass-fume',
  'builtin-liquid-glass-relief',
]

export type LabInk = GlassPreviewMode

/** Each scene's worst glass text ratio for the preset in one mode, at two decimals. */
export function glassSceneRatios(data: Preset, mode: GlassPreviewMode): Record<PresetBackdrop, number> {
  return Object.fromEntries(glassBackdropOptions.map(({ value }) =>
    [value, Math.round(glassContrastOnScene(data, mode, glassSceneRanges[value][mode]) * 100) / 100])) as Record<PresetBackdrop, number>
}

/**
 * The preview scene for a glass preset. The starting preset's own scene stays while the
 * preset's text reads there at 4.5:1, or at least as well as the unedited preset did;
 * otherwise, and without a starting preset, the scene the text reads best on, ties in
 * the menu order.
 */
export function pickGlassScene(data: Preset, mode: GlassPreviewMode, startingPresetId?: StartingPresetId): PresetBackdrop {
  const ratios = glassSceneRatios(data, mode)
  if (startingPresetId) {
    const own = glassPresetBackdrop(startingPresetId, mode)
    const reference = glassSceneRatios(getCatalog('0.1.0').startingPresets[startingPresetId], mode)[own]
    if (ratios[own] >= Math.min(4.5, reference)) return own
  }
  const best = Math.max(...Object.values(ratios))
  return glassBackdropOptions.find(({ value }) => ratios[value] === best)!.value
}

function sameColor(a: string | undefined, b: string) {
  return a !== undefined && normalizeColor(a) === normalizeColor(b)
}

/** The lab preset this preset still is, unedited: same design values and colours. */
function uneditedLabPreset(data: Preset): StartingPresetId | null {
  const catalog = getCatalog(data.catalogRelease)
  return labStartingPresets.find((id) => {
    const reference = catalog.startingPresets[id]
    const designKeys = Object.keys(reference.design) as (keyof Preset['design'])[]
    return designKeys.every((key) => (data.design[key] ?? 0) === (reference.design[key] ?? 0))
      && (['light', 'dark'] as const).every((mode) => Object.entries(reference.modes[mode])
        .every(([key, color]) => sameColor(data.modes[mode][key as keyof Preset['modes']['light']], color)))
  }) ?? null
}

/**
 * The lab ink replaces the text plate for an unedited lab preset over its own scene in
 * that mode, the scene its ink was tuned against. Other presets and scenes keep the plate.
 */
export function labInkFor(data: Preset, mode: GlassPreviewMode, scene: PresetBackdrop): LabInk | null {
  if (data.design?.transparency === 'reduced') return null
  const lab = uneditedLabPreset(data)
  return lab && glassPresetBackdrop(lab, mode) === scene ? mode : null
}

/**
 * The "Preview backdrop" options with each scene's ratio in its name: "Brume, 6.8:1",
 * "(auto)" on the automatic scene and ", below 4.5:1" in words on a failing one. With
 * reduced transparency the surfaces are opaque, so every scene shows the same ratio.
 */
export function glassBackdropMenu(data: Preset, mode: GlassPreviewMode, auto: PresetBackdrop, reduced: boolean): { value: PresetBackdrop; label: string }[] {
  const rated = reduced ? { ...data, design: { ...data.design, transparency: 'reduced' } } as Preset : data
  const ratios = glassSceneRatios(rated, mode)
  return glassBackdropOptions.map(({ value, label }) => ({
    value,
    label: `${label}, ${ratios[value].toFixed(1)}:1${value === auto ? ' (auto)' : ''}${ratios[value] < 4.5 ? ', below 4.5:1' : ''}`,
  }))
}
