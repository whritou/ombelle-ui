/**
 * Stable notice codes for `--json` output (PUB-06). Plans carry notices as text; the code is derived
 * here from the text's fixed opening, so every notice the CLI writes has exactly one code. Tools match
 * the code; the message stays free to improve.
 */
export const noticeCodes = [
  'GLASS_ACCESSIBILITY_CAVEAT',
  'GLASS_FILTER_MOUNT',
  'GLASS_CONTRAST',
  'SHADCN_UTILITY_ADOPTED',
  'DEPENDENCY_KEPT',
  'FILE_REFRESHED',
  'FONT_CSS_MANUAL',
  'FONT_PACKAGES_UNUSED',
  'THEME_PALETTE_ONLY',
  'INTERRUPTED_OPERATION',
  'CATALOG_FILE_REMOVED',
  'BLOCK_COMPONENT_EDITED',
  'BLOCK_COMPONENT_MISSING',
  'DEPENDENCY_RUNTIME_UNAVAILABLE',
  'REACT_UNTESTED_MAJOR',
  'RUNTIME_UNTESTED_MAJOR',
  'NOTICE',
] as const
export type NoticeCode = (typeof noticeCodes)[number]
export type Notice = { code: NoticeCode; message: string }

const openings: [RegExp, NoticeCode][] = [
  [/^Accessibility not guaranteed: liquid glass/, 'GLASS_ACCESSIBILITY_CAVEAT'],
  [/^mount <LiquidGlassFilter \/>/, 'GLASS_FILTER_MOUNT'],
  [/^Liquid glass text contrast fails/, 'GLASS_CONTRAST'],
  [/^adopt \S+ \(generated by shadcn\)$/, 'SHADCN_UTILITY_ADOPTED'],
  [/^keep \S+@\S+(?:,| \()/, 'DEPENDENCY_KEPT'],
  [/^refresh \S+ \(unedited since install/, 'FILE_REFRESHED'],
  [/^The style file is not managed here/, 'FONT_CSS_MANUAL'],
  [/^Font packages this theme no longer imports/, 'FONT_PACKAGES_UNUSED'],
  [/^Palette only:/, 'THEME_PALETTE_ONLY'],
  [/^An interrupted operation left/, 'INTERRUPTED_OPERATION'],
  [/^no longer generated: /, 'CATALOG_FILE_REMOVED'],
  [/^\S+ was edited after install; .+ uses it as is$/, 'BLOCK_COMPONENT_EDITED'],
  [/^\S+ needs \S+; run ombelle add /, 'BLOCK_COMPONENT_MISSING'],
  [/^Dependency install unavailable: /, 'DEPENDENCY_RUNTIME_UNAVAILABLE'],
  [/^React .* is newer than the versions this release was tested with/, 'REACT_UNTESTED_MAJOR'],
  [/^(?:Node|Bun) \S+ is newer than the versions this release was tested with/, 'RUNTIME_UNTESTED_MAJOR'],
]
export function noticeCode(message: string): NoticeCode {
  return openings.find(([pattern]) => pattern.test(message))?.[1] ?? 'NOTICE'
}
export const toNotices = (messages: readonly string[]): Notice[] =>
  messages.map((message) => ({ code: noticeCode(message), message }))
