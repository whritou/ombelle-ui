import { it, expect } from 'vitest'
import fs from 'node:fs/promises'
import path from 'node:path'
import { FoundationError } from '@ombelle/contracts'
import { createProject } from '../../../tests/helpers/projects.js'
import { exitCodes, runCli } from '../src/main.js'
import { parseArgs } from '../src/args.js'
import { noticeCode } from '../src/notices.js'
import { refreshNotice } from '../src/plan/components.js'
import { cliVersion } from '../src/version.js'
import cliPackage from '../package.json' with { type: 'json' }

async function run(args: string[]) {
  let stdout = '', stderr = ''
  const code = await runCli(args, { stdout: (text) => { stdout += text }, stderr: (text) => { stderr += text } })
  return { code, stdout, stderr }
}

it('prints the package version with --version, in text and JSON (PUB-16)', async () => {
  expect(cliVersion).toBe(cliPackage.version)
  expect(await run(['--version'])).toMatchObject({ code: 0, stdout: cliPackage.version })
  const json = await run(['--version', '--json'])
  expect(JSON.parse(json.stdout)).toEqual({ outputVersion: 1, command: 'version', status: 'success', version: cliPackage.version })
})

it('reads --flag=value, refuses unknown single-dash tokens and flags a command does not take (PUB-16)', () => {
  expect(parseArgs(['add', 'button', '--cwd=app', '--dry-run'])).toMatchObject({ command: 'add', operands: ['button'], flags: { '--cwd': 'app', '--dry-run': true } })
  expect(parseArgs(['add', 'button', '--overwrite=src/x.tsx'])).toMatchObject({ resolutions: [['overwrite', 'src/x.tsx']] })
  expect(() => parseArgs(['add', '-y'])).toThrow(expect.objectContaining({ code: 'INVALID_DATA', message: 'Unknown flag', path: '-y' }))
  expect(() => parseArgs(['add', 'button', '--yes=true'])).toThrow(expect.objectContaining({ message: '--yes takes no value' }))
  expect(() => parseArgs(['info', '--yes'])).toThrow(expect.objectContaining({ message: '--yes is not an option of info' }))
  expect(() => parseArgs(['update', '--beside', 'x'])).toThrow(expect.objectContaining({ message: '--beside is not an option of update' }))
  expect(parseArgs(['preset', 'apply', 'p.json', '--only', 'theme'])).toMatchObject({ command: 'preset apply', operands: ['p.json'] })
  expect(parseArgs(['-h'])).toEqual({ kind: 'help' })
})

it('refuses theme add with a second preset through --preset instead of ignoring it (PUB-16)', async () => {
  const result = await run(['theme', 'add', 'a.json', '--preset', 'b.json', '--json'])
  expect(result.code).toBe(2)
  expect(JSON.parse(result.stdout)).toMatchObject({ outputVersion: 1, command: 'theme add', status: 'error', error: { code: 'INVALID_DATA', path: '--preset' } })
})

it('reports an empty command for a parse failure rather than the first token (PUB-06)', async () => {
  const result = await run(['--cwd', 'x', '--json'])
  expect(JSON.parse(result.stdout)).toMatchObject({ outputVersion: 1, command: '', status: 'error', error: { code: 'INVALID_DATA', message: 'Choose a command' } })
})

it('maps INVALID_REFERENCE to exit 2 like other invalid input (PUB-07)', () => {
  expect(exitCodes.INVALID_REFERENCE).toBe(2)
  expect(Object.keys(exitCodes).sort()).toEqual([
    'DEPENDENCY_FAILURE', 'FILE_CONFLICT', 'INTERNAL_ERROR', 'INVALID_DATA', 'INVALID_REFERENCE', 'RESOLUTION_FAILURE',
    'STYLE_UNAVAILABLE', 'UNKNOWN_COMPONENT', 'UNSUPPORTED_PROJECT', 'UNSUPPORTED_RELEASE',
  ])
  expect(new FoundationError('INVALID_REFERENCE', 'x').code).toBe('INVALID_REFERENCE')
})

it('prints the next action of every error in text output (INS-02)', async () => {
  const root = await createProject('vite')
  try {
    const result = await run(['add', 'button', '--cwd', root, '--dry-run'])
    expect(result.code).toBe(3)
    expect(result.stderr).toBe('UNSUPPORTED_PROJECT: Initialize a saved project preset first (' + (await fs.realpath(root)) + ')\nNext: Run init --preset <file|code>.')
  } finally {
    await fs.rm(root, { recursive: true, force: true })
  }
})

it('refuses an invalid dependency timeout before planning (PUB-08)', async () => {
  const previous = process.env.OMBELLE_DEPENDENCY_TIMEOUT_SECONDS
  process.env.OMBELLE_DEPENDENCY_TIMEOUT_SECONDS = 'soon'
  try {
    const result = await run(['add', 'button', '--cwd', path.resolve('does-not-exist'), '--json'])
    expect(JSON.parse(result.stdout).error).toMatchObject({ code: 'INVALID_DATA', path: 'OMBELLE_DEPENDENCY_TIMEOUT_SECONDS' })
  } finally {
    if (previous === undefined) delete process.env.OMBELLE_DEPENDENCY_TIMEOUT_SECONDS
    else process.env.OMBELLE_DEPENDENCY_TIMEOUT_SECONDS = previous
  }
})

