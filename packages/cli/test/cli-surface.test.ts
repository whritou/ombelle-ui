// PUB-05: a document from a newer release is named as such, with the way forward, not a bare INVALID_DATA.
it.each([
  ['an unknown style family', { styleFamily: 'aurora' }, '/styleFamily'],
  ['a newer schemaVersion', { schemaVersion: '1.2' }, '/schemaVersion'],
  ['an unknown field', { gradient: true }, '/gradient'],
])('reports a preset with %s as a newer document (exit 3)', async (_, change, pointer) => {
  const directory = await fs.mkdtemp(path.join((await import('node:os')).tmpdir(), 'ombelle-newer-'))
  try {
    const preset = JSON.parse(await fs.readFile(path.resolve('packages/catalog/src/presets/flat.json'), 'utf8'))
    await fs.writeFile(path.join(directory, 'newer.json'), JSON.stringify({ ...preset, ...change }))
    const result = await run(['init', '--preset', path.join(directory, 'newer.json'), '--cwd', directory, '--json'])
    expect(result.code).toBe(3)
    expect(JSON.parse(result.stdout).error).toMatchObject({
      code: 'UNSUPPORTED_RELEASE',
      path: pointer,
      message: expect.stringContaining('does not know; it comes from a newer Ombelle release'),
      nextAction: expect.stringContaining('npx @ombelle-ui/cli@latest'),
    })
  } finally {
    await fs.rm(directory, { recursive: true, force: true })
  }
})
it('reports a lock written by a newer CLI as a newer release (PUB-05)', async () => {
  const root = await createProject('vite')
  try {
    await fs.writeFile(path.join(root, 'ui-library.lock.json'), JSON.stringify({ lockVersion: 2 }))
    const result = await run(['info', '--cwd', root, '--json'])
    expect(result.code).toBe(3)
    expect(JSON.parse(result.stdout).error).toMatchObject({ code: 'UNSUPPORTED_RELEASE', path: 'ui-library.lock.json' })
  } finally {
    await fs.rm(root, { recursive: true, force: true })
  }
})
