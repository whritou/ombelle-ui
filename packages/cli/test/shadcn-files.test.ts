import { it, expect, afterEach } from 'vitest'
import fs from 'node:fs/promises'
import path from 'node:path'
import { compile } from '@ombelle/compiler'
import { getCatalog } from '@ombelle/catalog'
import { createProject } from '../../../tests/helpers/projects.js'
import { inspectProject } from '../src/project/inspect.js'
import { planAdd } from '../src/plan/components.js'
const roots: string[] = []
afterEach(async () => {
  for (const root of roots.splice(0))
    await fs.rm(root, { recursive: true, force: true })
})
const shadcnUtility = 'export { cn } from "cn"\n'
const build = (componentIds: string[]) =>
  compile({
    preset: getCatalog('0.1.0').presets.flat,
    componentIds: componentIds as never,
    catalogRelease: '0.1.0',
    compilerVersion: '0.1.0',
  })
async function project(files: Record<string, string>, utilsAlias?: string) {
  const root = await createProject('vite')
  roots.push(root)
  if (utilsAlias) {
    const file = path.join(root, 'components.json'),
      c = JSON.parse(await fs.readFile(file, 'utf8'))
    c.aliases.utils = utilsAlias
    await fs.writeFile(file, JSON.stringify(c))
  }
  for (const [p, content] of Object.entries(files)) {
    await fs.mkdir(path.dirname(path.join(root, p)), { recursive: true })
    await fs.writeFile(path.join(root, p), content)
  }
  return root
}
const changeAt = (plan: Awaited<ReturnType<typeof planAdd>>, p: string) =>
  plan.changes.find((c) => c.path === p)!

it('adopts the utility generated by the pinned shadcn', async () => {
  const plan = await planAdd(await inspectProject(await project({ 'src/lib/utils.ts': shadcnUtility })), await build(['badge']))
  expect(changeAt(plan, 'src/lib/utils.ts').action).toBe('update')
  expect(plan.changes.filter((c) => c.action === 'conflict')).toEqual([])
  expect(plan.notices).toContain('adopt src/lib/utils.ts (generated by shadcn)')
})

it('still conflicts on an edited utility', async () => {
  const plan = await planAdd(
    await inspectProject(await project({ 'src/lib/utils.ts': shadcnUtility + '// mine\n' })),
    await build(['badge']),
  )
  expect(changeAt(plan, 'src/lib/utils.ts').action).toBe('conflict')
  expect(plan.notices).toEqual([])
})

it('adopts the utility at a custom utils alias', async () => {
  const plan = await planAdd(
    await inspectProject(await project({ 'src/lib/cn.ts': shadcnUtility }, '@/lib/cn')),
    await build(['badge']),
  )
  expect(changeAt(plan, 'src/lib/cn.ts').action).toBe('update')
  expect(plan.notices).toContain('adopt src/lib/cn.ts (generated by shadcn)')
})

it('never adopts component files by content', async () => {
  const plan = await planAdd(
    await inspectProject(await project({ 'src/components/ui/button.tsx': shadcnUtility })),
    await build(['button']),
  )
  expect(changeAt(plan, 'src/components/ui/button.tsx').action).toBe('conflict')
})
