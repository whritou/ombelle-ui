import fs from 'node:fs/promises'
import { compileComponentRecipe, compileRecipe, componentRecipeFontRoles } from '@ombelle/compiler'
import { componentRecipeComponents, styleFamilies } from '@ombelle/contracts'
import { defaultButtonRecipe, defaultCatalogRecipe, precompiledDefaults } from '../apps/www/src/editor/precompiled-defaults.js'

/**
 * Compiles each component editor's default recipe in each precompiled family, as the editor's first compile
 * would, for the editor preview to show before that compile arrives. One JSON file per component and family.
 */
export async function writeEditorDefaults(directory: string) {
  await fs.rm(directory, { recursive: true, force: true })
  for (const { component, family } of precompiledDefaults()) {
    const result = component === 'button'
      ? await compileRecipe({ recipe: defaultButtonRecipe(family) })
      : await compileComponentRecipe({ recipe: defaultCatalogRecipe(component, family) })
    await fs.mkdir(`${directory}/${component}`, { recursive: true })
    await fs.writeFile(`${directory}/${component}/${family}.json`, JSON.stringify(result) + '\n')
  }
}

/**
 * Which font roles each component shows in each family (componentRecipeFontRoles), as a module the
 * component editors import instead of the compiler, which needs every template to answer.
 */
export async function writeComponentFontRoles(file: string) {
  const roles = Object.fromEntries(componentRecipeComponents.map((component) => [component,
    Object.fromEntries(styleFamilies.map((family) => [family, componentRecipeFontRoles(component, family)]))]))
  await fs.writeFile(file, '// Generated by scripts/generate-editor-defaults.ts.\n' +
    "import type { ComponentRecipeId, StyleFamily } from '@ombelle/contracts'\n" +
    'export const componentFontRoles: Record<ComponentRecipeId, Record<StyleFamily, { heading: boolean; mono: boolean }>> = ' +
    JSON.stringify(roles) + '\n')
}
