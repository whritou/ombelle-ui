// Older CLIs (blocks spec): the published 1.0 CLI does not know blocks. In a project whose lock a 1.1 CLI wrote
// block records into, it keeps those records, reports the files as "not generated" (a warning, not a failure)
// and leaves them alone on `update`. Needs registry access to install @ombelle-ui/cli@1.0.0.
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { blockManifest, getCatalog } from '@ombelle/catalog'
import { createProject } from '../helpers/projects.js'
import { runBuiltCli, jsonRecord, runtimeIdentity } from '../helpers/cli-runtime.js'
import { runNative } from '../helpers/bun-command.js'

const execute = promisify(execFile)
const preset = path.resolve('packages/catalog/src/presets/flat.json')
const files = ['src/components/blocks/login-01.tsx', 'src/components/blocks/login-01.css']
const logical = ['blocks/login-01.tsx', 'blocks/login-01.css']

describe.skipIf(!process.env.OMBELLE_REGISTRY_TESTS)('the published 1.0 CLI on a lock with blocks', () => {
  let installRoot = ''
  let oldCli = ''
  const roots: string[] = []
  beforeAll(async () => {
    installRoot = await fs.mkdtemp(path.join(os.tmpdir(), 'ombelle-cli-1.0-'))
    await fs.writeFile(path.join(installRoot, 'package.json'), '{"private":true}')
    const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm'
    await execute(npm, ['install', '--ignore-scripts', '--no-audit', '--no-fund', '@ombelle-ui/cli@1.0.0'], {
      cwd: installRoot, windowsHide: true, shell: process.platform === 'win32', timeout: 240000,
    })
    const dir = path.join(installRoot, 'node_modules', '@ombelle-ui', 'cli')
    const manifest = JSON.parse(await fs.readFile(path.join(dir, 'package.json'), 'utf8'))
    expect(manifest.version).toBe('1.0.0')
    const bin = typeof manifest.bin === 'string' ? manifest.bin : Object.values<string>(manifest.bin)[0]
    oldCli = path.join(dir, bin)
  }, 300000)
  afterAll(async () => {
    for (const root of [installRoot, ...roots]) if (root) await fs.rm(root, { recursive: true, force: true })
  })

  it('keeps block records through add and update, and reports block files without failing doctor', async () => {
    const root = await createProject('vite')
    roots.push(root)
    const read = (file: string) => fs.readFile(path.join(root, file), 'utf8')
    // Keeps the runs offline: every dependency the components declare is already in package.json.
    const pkg = JSON.parse(await read('package.json'))
    const ids = new Set([...Object.values(blockManifest).flatMap((meta) => meta.components), 'badge' as const])
    for (const id of ids)
      for (const dependency of getCatalog('0.1.0').templates[id].dependencies) pkg.dependencies[dependency.name] = dependency.version
    await fs.writeFile(path.join(root, 'package.json'), JSON.stringify(pkg))
    const current = (args: string[]) => runBuiltCli('node', [...args, '--cwd', root, '--json'], root)
    const older = async (args: string[]) => {
      const identity = await runtimeIdentity('node')
      const result = await runNative(identity.executable, [oldCli, ...args, '--cwd', root, '--json'], root, {})
      return { ...result, data: JSON.parse(result.output) as unknown }
    }

    expect((await current(['init', '--preset', preset, '--yes'])).code).toBe(0)
    const added = await current(['add', 'login-01', '--yes'])
    expect(added.code, added.output).toBe(0)
    const blockBytes = await Promise.all(files.map(read))
    const lockBlocks = async () => {
      const lock = JSON.parse(await read('ui-library.lock.json'))
      return files.map((file) => lock.artifacts[file])
    }
    const recorded = await lockBlocks()
    expect(recorded.map((r) => r.logicalPath)).toEqual(logical)
    expect(recorded.map((r) => r.kind)).toEqual(['block', 'block'])

    const badge = await older(['add', 'badge', '--yes'])
    expect(badge.code, badge.output).toBe(0)
    await expect(read('src/components/ui/badge.tsx')).resolves.toBeTruthy()
    expect(await lockBlocks()).toEqual(recorded)
    expect(await Promise.all(files.map(read))).toEqual(blockBytes)

    const doctor = await older(['doctor'])
    expect(doctor.code, doctor.output).toBe(0)
    const body = jsonRecord(doctor.data)
    expect(body.status).toBe('success')
    const checks = body.checks as { id: string; status: string; message: string; path?: string }[]
    const notGenerated = checks.filter((c) => c.status === 'warn' && c.message.endsWith('no longer generated by the catalog'))
    expect(notGenerated.map((c) => c.path).sort(), JSON.stringify(body)).toEqual([...files].sort())
    expect(checks.filter((c) => c.status === 'fail')).toEqual([])

    const updated = await older(['update', '--yes'])
    expect(updated.code, updated.output).toBe(0)
    expect(await Promise.all(files.map(read))).toEqual(blockBytes)
    expect(await lockBlocks()).toEqual(recorded)
  }, 300000)
})
